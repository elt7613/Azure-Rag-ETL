"""Generate `.env.example`, and re-order `.env` to match it.

Both files are derived from `rag.config.Settings` rather than maintained by
hand, because hand-maintained pairs drift: a setting gets added to one, the
other is forgotten, and the next person to set the project up discovers it by
hitting a default they did not know existed. Here the field list, the order and
the grouping all come from the class itself, so a new setting appears in both
files the moment it exists.

    python scripts/gen_env.py            # rewrite .env.example, re-order .env
    python scripts/gen_env.py --check    # verify both are current, change nothing

`--check` is what the test uses.

Only `.env.example` gets generated values. `.env` keeps whatever is already in
it -- it holds real credentials, and regenerating it would either wipe them or
print them into a template. Its keys are re-ordered to match, and any setting
missing from it is appended with its default so the two files stay comparable
line by line.
"""
