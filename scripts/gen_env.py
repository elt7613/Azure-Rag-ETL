def _default_for(name: str, field) -> str:
    """The value `.env.example` should show for a field."""
    if field.is_required():
        return ""
    default = field.default_factory() if field.default_factory else field.default
    if default is None:
        return ""
    if isinstance(default, bool):
        return "true" if default else "false"
    if isinstance(default, (list, dict)):
        import json

        return json.dumps(default, separators=(",", ":"))
    return str(default)


def render_example() -> str:
    lines = [HEADER]
    for name, field in Settings.model_fields.items():
        if name in SECTIONS:
            lines.append(f"\n# ---------------------------------------------------------------------\n"
                         f"# {SECTIONS[name]}\n"
                         f"# ---------------------------------------------------------------------")
        doc = DOCS.get(name)
        if doc is None:  # pragma: no cover - guarded by the test
            raise SystemExit(
                f"scripts/gen_env.py: no description for setting {name!r}. "
                "Add one to DOCS so the template explains every field."
            )
        lines.append(f"# {doc}")
        lines.append(f"{name.upper()}={_default_for(name, field)}")
    return "\n".join(lines).rstrip() + "\n"


def _existing_values(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text().splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key, value = stripped.split("=", 1)
            values[key.strip()] = value
    return values


def render_env(existing: dict[str, str]) -> str:
    """`.env` in the same order, grouping and comments as the template.

    The comments are repeated here rather than left only in `.env.example`
    because this is the file people actually edit -- being told what
    `SUFFICIENCY_THRESHOLD` means at the moment you are changing it is worth
    more than a duplicate line in a generated file.
    """
    lines = [
        "# Local configuration.",
        "#",
        "# Same fields, order and comments as .env.example -- both are generated",
        "# from `rag.config.Settings` by `python scripts/gen_env.py`, which keeps",
        "# the values already set here. Real credentials live in this file and it",
        "# is gitignored; never commit it.",
    ]
    for name, field in Settings.model_fields.items():
        if name in SECTIONS:
            lines.append(f"\n# ---------------------------------------------------------------------\n"
                         f"# {SECTIONS[name]}\n"
                         f"# ---------------------------------------------------------------------")
        key = name.upper()
        lines.append(f"# {DOCS[name]}")
        lines.append(f"{key}={existing.get(key, _default_for(name, field))}")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Verify both files are current; write nothing.")
    args = parser.parse_args()

    example_path, env_path = ROOT / ".env.example", ROOT / ".env"
    example = render_example()
    env = render_env(_existing_values(env_path))

    if args.check:
        stale = []
        if not example_path.exists() or example_path.read_text() != example:
            stale.append(".env.example")
        if env_path.exists() and env_path.read_text() != env:
            stale.append(".env")
        if stale:
            print(f"stale: {', '.join(stale)} -- run `python scripts/gen_env.py`")
            return 1
        print("env files are current")
        return 0

    example_path.write_text(example)
    print(f"wrote {example_path.relative_to(ROOT)}")
    if env_path.exists():
        env_path.write_text(env)
        print(f"re-ordered {env_path.relative_to(ROOT)} (values preserved)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
